-- Necesaria para combinar "=" (nutricionista) con "&&" (solapamiento) en una restricción de exclusión.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- PostgreSQL no trae un tipo de rango para TIME; lo definimos para poder comparar franjas horarias.
CREATE TYPE timerange AS RANGE (subtype = time);

-- Franjas semanales en las que un nutricionista atiende (hora local de la clínica).
CREATE TABLE availability (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nutritionist_id BIGINT   NOT NULL REFERENCES users (id),
    day_of_week     SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7), -- ISO: 1 = lunes ... 7 = domingo
    start_time      TIME     NOT NULL,
    end_time        TIME     NOT NULL,
    CONSTRAINT ck_availability_range CHECK (start_time < end_time),
    -- Un nutricionista no puede tener dos franjas que se pisen el mismo día.
    CONSTRAINT ex_availability_no_overlap EXCLUDE USING gist (
        nutritionist_id WITH =,
        day_of_week WITH =,
        timerange(start_time, end_time) WITH &&
    )
);

CREATE TABLE appointments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nutritionist_id BIGINT      NOT NULL REFERENCES users (id),
    patient_id      BIGINT      NOT NULL REFERENCES users (id),
    start_at        TIMESTAMPTZ NOT NULL,
    end_at          TIMESTAMPTZ NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
                    CHECK (status IN ('SCHEDULED', 'CANCELLED', 'COMPLETED')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_appointments_range CHECK (start_at < end_at),
    -- Red de seguridad contra carreras: la base rechaza dos turnos activos que se solapen.
    CONSTRAINT ex_appointments_nutritionist_no_overlap EXCLUDE USING gist (
        nutritionist_id WITH =,
        tstzrange(start_at, end_at) WITH &&
    ) WHERE (status <> 'CANCELLED'),
    -- Un paciente tampoco puede estar en dos turnos a la vez.
    CONSTRAINT ex_appointments_patient_no_overlap EXCLUDE USING gist (
        patient_id WITH =,
        tstzrange(start_at, end_at) WITH &&
    ) WHERE (status <> 'CANCELLED')
);

CREATE INDEX idx_appointments_nutritionist_start ON appointments (nutritionist_id, start_at);
CREATE INDEX idx_appointments_patient_start ON appointments (patient_id, start_at);
